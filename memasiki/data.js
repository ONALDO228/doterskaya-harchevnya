/* ==========================================================================
   data.js — БАЗА ДАННЫХ РАЗДЕЛА «МЕМАСИКИ»

   Здесь ТОЛЬКО данные. Ни одного тега, ни одного стиля.
   Разделение простое:
     data.js   — что показывать (список рецептов),
     app.js    — как показывать (функции-компоненты),
     *.css     — какого это цвета.

   Почему данные в JS, а не вписаны в HTML руками:
    карточек шестнадцать, а фильтров два, и значения для них берутся из
    самих рецептов. Если бы вёрстка была ручной, каждую комбинацию
    фильтра пришлось бы описывать отдельно для каждой карточки. Здесь
    фильтр просто отбирает элементы массива — и карточка появляется сама,
    потому что её рисует код.

    Категории («Коктейли», «Закуски», «Горячее», «Десерты», «Мемори»)
    нигде не переписываются: app.js собирает кнопки фильтра из тех
    строк, что лежат в поле category. Добавил рецепт с новой категорией
    — кнопка появилась сама.

   Поля одного рецепта:
     id             — внутренний номер,
     slug           — часть адреса страницы-легенды,
     title          — заголовок на карточке,
     category       — строка фильтра («Коктейли», «Закуски» …),
     mmr            — сложность в рангах Dota, для фильтра по MMR,
     timing         — сколько ждать,
     stack          — сколько ингредиентов (stack = «стек» предметов),
     tags           — хэштеги,
     ingredients    — массив { name, amount, role },
     steps          — массив строк, шаги по порядку,
     memeQuotes     — цитаты,
      img            — картинка. ФАЙЛОВ ПОКА НЕТ в img/cocktails/,
                       img/snacks/, img/hot/, img/desserts/ и img/memos/,
                       поэтому app.js рисует эмодзи из поля
                       art: картинка вставляется ПОВЕРХ эмодзи, а если
                       файла нет — событие error убирает её, и под ней
                       уже лежит заглушка. Никаких серых квадратов.
                       Картинка подключится сама, как только файл
                       появится по этому пути,

     badge          — плашка на карточке («🎮 ЛЕГЕНДА»),
     isFeatured     — показывать крупно, первым,
      ageRestriction — '18+', '12+' или пусто. Строка '18+' значит: рецепт
                       не показывать никому, кто ответил «мне меньше 18»;
                       '12+' — показывать всем, это только метка возраста
                       на карточке, замка под ней нет,
     link           — куда ведёт кнопка «читать». Если поля нет,
                      карточка не кликабельна.
   ========================================================================== */


/* ==========================================================================
   store.js — ХРАНИЛИЩЕ ДАННЫХ САЙТА (localStorage)

   ЧТО ТАКОЕ localStorage.
   У браузера есть маленькая база «ключ → строка», привязанная к
   адресу сайта. Записал — закрыл вкладку — вернулся, данные на месте.
   Именно так работает «запомнить меня» на крупных сайтах, просто
   там база на сервере, а не в браузере.

   ДВА ОГРАНИЧЕНИЯ, О КОТОРЫХ НАДО ПОМНИТЬ:
   1) localStorage живёт В ОДНОМ браузере на ОДНОМ устройстве.
      Отзывы и рецепты, добавленные тобой, не увидит никто другой.
      Чтобы данные были общими для всех, нужен сервер с базой
      (или готовый сервис вроде Firebase / Supabase). Этот файл
      устроен так, что потом можно поменять только Store.read/write,
      а весь остальной код сайта оставить как есть.
   2) Внутрь можно класть ТОЛЬКО строки. Объекты и массивы поэтому
      превращаем в текст: JSON.stringify() при записи, JSON.parse()
      при чтении. JSON — это просто способ записать объект буквами.

   ЗАЧЕМ НУЖЕН ОТДЕЛЬНЫЙ ФАЙЛ.
   Ниже лежат ОДНИ низкие функции: прочитать, записать, сделать id,
   посчитать хэш, красиво показать дату. Аккаунты, отзывы и рецепты
   пользуются ими, а не обращаются к localStorage напрямую. Плюс:
   если завтра переезжаешь на сервер, править придётся один файл.

   ПОРЯДОК ПОДКЛЮЧЕНИЯ скриптов на странице (важно!):
     store.js  →  auth.js  →  reviews.js / recipes-user.js
   defer выполняет файлы СТРОГО в том порядке, в котором они
   написаны, так что Store будет готов раньше, чем его позовут.
   ========================================================================== */

var Store = {

  /* ПРИСТАВКА К ЛЮБОМУ КЛЮЧУ.
     Все ключи на сайте будут начинаться с «dh:» (дотерская харчевня).
     localStorage общий для всего сайта: если рядом откроешь другой
     проект на том же адресе, чужие ключи не столкнутся с нашими. */
  PREFIX: 'dh:',

  /* ------------------------------------------------------------
     ПРОЧИТАТЬ.
     Ключа нет (первый заход на сайт) или хранилище сломалось —
     возвращаем fallback, а не падаем. JSON.parse кидает исключение,
     если внутри мусор (например, запись оставил другой скрипт),
     поэтому всё под try/catch.
     ------------------------------------------------------------ */
  read: function (key, fallback) {
    try {
      var raw = window.localStorage.getItem(Store.PREFIX + key);

      /* getItem несуществующего ключа возвращает null.
         Отдельная проверка нужна, потому что JSON.parse(null)
         вернёт null, а JSON.parse('null') — тоже null, и fallback
         до fallback'а не дошёл бы. */
      if (raw === null) {
        return fallback;
      }
      return JSON.parse(raw);
    } catch (e) {
      /* Сюда попадаем, если localStorage запрещён браузером
         (приватный режим, некоторые политики) или внутри мусор. */
      return fallback;
    }
  },

  /* ------------------------------------------------------------
     ЗАПИСАТЬ.
     Пишем всегда JSON.stringify(value) — объект превращается в
     текст вида {"a":1}. Возвращаем true/false, чтобы вызывающий код
     мог сказать «не сохранилось, место кончилось».
     ------------------------------------------------------------ */
  write: function (key, value) {
    try {
      window.localStorage.setItem(Store.PREFIX + key, JSON.stringify(value));
      return true;
    } catch (e) {
      /* Самое частое: превышен лимит ~5 МБ. Для отзывов и рецептов
         нереально, но код от этого не должен падать молча. */
      return false;
    }
  },

  /* УДАЛИТЬ ключ целиком (например, «выйти из аккаунта»). */
  remove: function (key) {
    try {
      window.localStorage.removeItem(Store.PREFIX + key);
    } catch (e) {
      /* нет хранилища — нечего и удалять */
    }
  },

  /* ------------------------------------------------------------
     УНИКАЛЬНЫЙ ИДЕНТИФИКАТОР.
     Любая запись (отзыв, рецепт, пользователь) обязана иметь своё
     имя, иначе «удалить этот отзыв» превратится в «удалить первый
     попавшийся».
     Math.random().toString(36) — дробь, записанная 36-ричной системой
     (цифры + буквы), получается коротко. Отрезаем хвост, приклеиваем
     время создания: два id, созданные в одну миллисекунду, всё равно
     различатся случайной частью.
     ------------------------------------------------------------ */
  uid: function (prefix) {
    var stamp = Date.now().toString(36);
    var random = Math.random().toString(36).slice(2, 8);
    return (prefix || 'id') + '-' + stamp + '-' + random;
  },

  /* ------------------------------------------------------------
   ХЭШ ПАРОЛЯ — ВНИМАНИЕ, ЭТО ДЕМО, А НЕ ЗАЩИТА.

   Идея: пароль в чистом виде хранить нельзя никогда. Хранят только
   «отпечаток» — результат необратимой функции. При входе считаем
   отпечаток введённого пароля и сравниваем с сохранённым.

   Здесь самая примитивная функция (djb2): сворачивает строку в одно
   число. Её задача — показать ПРИНЦИП, а не защитить.
   Почему это не защита:
     1) любой, кто открыл консоль браузера, читает localStorage как
        обычный текст и подбирает пароль за секунды;
     2) считается мгновенно — перебор миллионов вариантов не упрётся
        в лимит, как настоящий bcrypt/argon2;
     3) на статическом сайте (без сервера) пароль в любом случае
        проверяется В БРАУЗЕРЕ, то есть «секрет» лежит у пользователя.
   Настоящая регистрация = сервер + bcrypt/argon2 + https + куки-сессия.
   Соль (salt) — случайный набор символов, который приклеиваем к
   паролю перед хэшированием, чтобы у двух пользователей с одинаковым
   паролем отпечатки вышли разными.
   ------------------------------------------------------------ */
  hash: function (text) {
    var hash = 5381;
    for (var i = 0; i < text.length; i++) {
      /* hash * 33 + символ. Умножение через сдвиг — та же операция,
         только быстрее: (hash << 5) это hash * 32. */
      hash = ((hash << 5) + hash) + text.charCodeAt(i);
      /* |0 — превратить число обратно в 32-битное целое, иначе через
         пару тысяч символов оно стало бы дробным и «поплыло». */
      hash = hash | 0;
    }
    /* >>>0 — сделать беззнаковым, чтобы минус не превращался в
       «-» в итоговой строке. toString(16) — запись в 16-ричной системе. */
    return (hash >>> 0).toString(16);
  },

  /* СЛУЧАЙНАЯ СОЛЬ. Берём кусок от случайного id — длины достаточно. */
  salt: function () {
    return Store.uid('s');
  },

  /* ------------------------------------------------------------
     КРАСИВАЯ ДАТА ДЛЯ ПОДПИСЕЙ «30.09.2026, 14:05».
     new Date(число) — дата из миллисекунд с 1 января 1970.
     getMonth() считает ОТ НУЛЯ (0 = январь), поэтому +1.
     padStart(2, '0') — если цифра одна, дописать слева ноль:
     '9' → '09'. Иначе 3.7 выглядело бы как «3:7».
     ------------------------------------------------------------ */
  formatDate: function (timestamp) {
    var d = new Date(timestamp);
    function pad(n) {
      return String(n).padStart(2, '0');
    }
    return pad(d.getDate()) + '.' + pad(d.getMonth() + 1) + '.' + d.getFullYear() +
           ', ' + pad(d.getHours()) + ':' + pad(d.getMinutes());
  },

  /* ПРАВИЛЬНОЕ СКЛОНЕНИЕ: 1 день / 2 дня / 5 дней.
     В русском окончание зависит от последних двух цифр числа:
       11–14                      → родительный множественного (дней)
       последняя цифра 1          → день
       последняя цифра 2, 3, 4    → дня
       всё остальное (0, 5..9)    → дней
     Форма задаётся СПИСКОМ из трёх слов, а не дописывается к основе:
     «минуту/минуты/минут» и «час/часа/часов» не получаются из одного
     корня добавлением букв. */
  plural: function (count, forms) {
    /* forms = [для 1, для 2–4, для 5–0]. Индекс 0 используем для
       «одна минута», 1 — «2 минуты», 2 — «5 минут». */
    var n = Math.abs(count) % 100;
    var last = n % 10;
    if (n >= 11 && n <= 14) {
      return forms[2];
    }
    if (last === 1) {
      return forms[0];
    }
    if (last >= 2 && last <= 4) {
      return forms[1];
    }
    return forms[2];
  },

  /* «3 дня назад» — читать приятнее, чем дату.
     Считаем разницу в секундах, выбираем единицу и склоняем слово.
     Старше месяца показываем точную дату: «400 дней назад» — уже
     не информация, а шум. */
  timeAgo: function (timestamp) {
    var sec = Math.floor((Date.now() - timestamp) / 1000);

    if (sec < 60) {
      return 'только что';
    }

    var MINUTE = 60, HOUR = 3600, DAY = 86400;
    var value, forms;

    if (sec < HOUR) {
      value = Math.floor(sec / MINUTE);
      forms = ['минуту', 'минуты', 'минут'];
    } else if (sec < DAY) {
      value = Math.floor(sec / HOUR);
      forms = ['час', 'часа', 'часов'];
    } else if (sec < DAY * 31) {
      value = Math.floor(sec / DAY);
      forms = ['день', 'дня', 'дней'];
    } else {
      return Store.formatDate(timestamp);
    }

    return value + ' ' + Store.plural(value, forms) + ' назад';
  }
};

/* ==========================================================================
   script.js — ПЕРВЫЙ JAVASCRIPT САЙТА

   HTML  = СТРУКТУРА  (что где лежит)
   CSS   = ВНЕШНИЙ ВИД (какого цвета, где стоит)
   JS    = ПОВЕДЕНИЕ   (что происходит, когда пользователь кликнул)

   Как файл попадает на страницу (см. index.html):
     <script src="script.js" defer></script>
    defer = "дождись, пока браузер построит страницу, и только потом
    выполняй меня". Без defer скрипт отрабатывает ДО того, как тег
    кнопки вообще существует, querySelector возвращает null, и всё
    падает с "Cannot read properties of null". Это ошибка №1 у всех,
    кто начинает писать JS.

   ПОРЯДОК НА СТРАНИЦЕ: script.js подключён ПОСЛЕДНИМ, потому что
   смотрит в UserRecipes (файл recipes-user.js) — рецепты посетителей
   для случайного выбора.
   ========================================================================== */


/* СПИСОК РЕЦЕПТОВ САЙТА — те, что вписаны автором.
   Массив — это пронумерованный список значений внутри квадратных
   скобок. Нумерация starts with 0: recipes[0] — первый элемент.

   Каждая запись — ОБЪЕКТ: набор пар «ключ: значение».
   Здесь у рецепта два поля:
     file — куда идти (имя файла)
     name — как показать (название)

   ЗАЧЕМ ЭТОТ СПИСОК ВООБЩЕ НУЖЕН.
   Можно было бы вписать пять ссылок прямо в HTML и перемешивать их
   наугад числом от 1 до 5. Но тогда при добавлении шестого рецепта
   ты бы пошла править ДВА места: карточку в index.html и диапазон
   случайных чисел здесь. Забыла бы одно — кнопка иногда вела бы в
   несуществующую страницу.
   Тут список один: добавила рецепт = добавила одну строчку сюда. */
var recipes = [
  { file: 'recipe.html',     name: 'Борщ твоей мамки' },
  { file: 'bliny.html',      name: 'Блины мини пеки' },
  { file: 'salat.html',      name: 'Цезарь «Соло-рейндж»' },
  { file: 'carbonara.html',  name: 'Карбонара «Рапира»' },
  { file: 'pampasiki/pampe.html', name: 'Пампасики: 10 рецептов' },
  { file: 'memasiki/index.html',  name: 'Раздел «Мемасики»' }
];


/* ВЫБРАТЬ ОДИН РЕЦЕПТ НАУГАД.

   Функция — это кусок кода, который имеет имя и вызывается по нему.
   Объявить функцию ≠ запустить её. Строка ниже ничего не делает,
   пока её не позовут вот так: pickRecipe().

   Math.random() — число от 0 (включительно) до 1 (не включая 1).
   Умножаем на длину списка → получаем дробное от 0 до 4.
   Math.floor() — округление ВНИЗ: 3.9 превращает в 3.
   Итог: 0, 1, 2 или 3. Именно индексы существующих элементов.

   Почему не Math.round()? Он округляет ПО ПРАВИЛАМ, и 3.6 превратил
   в 4. А элемента с индексом 4 нет — recipes[4] вернул бы undefined,
   и на следующей строке вылезло бы "Cannot read properties of
   undefined (reading 'file')". Классическая ошибка на границе
   диапазона. */
function pickRecipe() {
  var pool = allRecipes();
  var index = Math.floor(Math.random() * pool.length);
  return pool[index];
}


/* ПОЛНЫЙ СПИСОК ДЛЯ ВЫБОРА = СВОИ + НАРОДНЫЕ.
   recipes-user.js отдаёт рецепты посетителей уже в нужном формате
   { file, name }, поэтому здесь только склеивание массивов.

   concat НЕ меняет исходные массивы, а возвращает новый — важно,
   иначе countRecipes() считал бы удвоенное количество после первого
   же вызова.

   Проверка typeof UserRecipes нужна, потому что файл может быть не
   подключён (страница без аккаунтов, или скрипт подключили один).
   Без неё страница падала бы с "UserRecipes is not defined". */
function allRecipes() {
  if (typeof UserRecipes !== 'undefined' && UserRecipes.forRandom) {
    return recipes.concat(UserRecipes.forRandom());
  }
  return recipes;
}


/* ПРИВЯЗАТЬ ДЕЙСТВИЕ К КНОПКЕ.

   querySelector находит ПЕРВЫЙ элемент по CSS-селектору. Селекторы
   здесь те же самые, что в style.css: #random-btn — это id="random-btn",
   точка .random — это class="random". JS и CSS ищут элементы одними и
   теми же способами, поэтому знание CSS уже наполовину окупилось.

   addEventListener('click', функция) — не «выполни сейчас», а
   «ЗАПОМНИ функцию и зови её каждый раз, когда по мне кликнули».
   Второй аргумент — это функция БЕЗ скобок. Напиши pickAndGo() с
   скобками — она выполнится один раз сразу при загрузке страницы,
   и пользователь никогда не узнает, что кнопка работала.

   location.href = ... — то же самое, что перейти по ссылке: браузер
   загружает указанный файл. */
function pickAndGo() {
  var chosen = pickRecipe();
  window.location.href = chosen.file;
}

var randomBtn = document.querySelector('#random-btn');

/* Страховка: если вдруг скрипт подключат на странице, где такой кнопки
   нет (например, на странице рецепта), querySelector вернёт null,
   а у null уже нельзя спросить addEventListener — будет красная ошибка
   в консоли. Проверка «кнопка нашлась?» молча пропускает лишние
   страницы вместо падения. */
if (randomBtn) {
  randomBtn.addEventListener('click', pickAndGo);
}


/* ПОДСЧЕТ РЕЦЕПТОВ В ТЕКСТЕ (мелочь, которая не даёт соврать).
   В index.html в предложении стоит пустоватый span:
     Сейчас в базе <span id="recipes-count">несколько</span> рецептов.
   Слово «несколько» — заглушка, JS заменяет её настоящим числом.

   Зачем не вписать цифру руками: впишешь «4», через неделю добавишь
   рецепт, про цифру забудешь — и сайт начнёт врать. Тут число
   берётся из allRecipes().length, то есть из того же списка, по
   которому кнопка реально работает. Врать он не может физически.

   textContent = «положи внутрь элемента такой-то текст».
   length у массива — количество элементов, у строки — количество
   символов. Это свойство, а не метод: скобки после него не пишут. */
function renderCount() {
  var countEl = document.querySelector('#recipes-count');
  if (countEl) {
    countEl.textContent = allRecipes().length;
  }
}

renderCount();


/* ПЕРЕРИСОВАТЬ ЧИСЛО ПОСЛЕ ТОГО, КАК КТО-ТО ДОБАВИЛ РЕЦЕПТ.
   Без этой строки счётчик показал бы «6», человек добавил бы свой
   рецепт, и до перезагрузки страницы цифра врала бы.
   Auth.subscribe — то же, чем пользуются отзывы: не лезть внутрь
   auth.js, а попросить позвать себя, когда что-то изменится. */
if (typeof Auth !== 'undefined' && Auth.subscribe) {
  Auth.subscribe(renderCount);
}


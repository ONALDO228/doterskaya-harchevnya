/* ==========================================================================
   ui.js — МЕЛКИЕ ПОМОЩНИКИ ДЛЯ РИСОВАНИЯ СТРАНИЦ

   Почему это отдельный файл: auth.js, reviews.js и recipes-user.js
   делают СОБРАЗИЕ — создают теги, вставляют текст, рисуют звёзды.
   Если написать это в каждом файле свой вариант, получится три
   копии одной функции, и правку надо будет делать трижды.
   Правила:
     store.js — ДАННЫЕ   (как читать и писать)
     ui.js    — КИРПИЧИ  (как собрать тег)
     auth.js / reviews.js / recipes-user.js — СБОРКА КОНКРЕТНЫХ БЛОКОВ

   ПОРЯДОК ПОДКЛЮЧЕНИЯ:
     store.js → ui.js → auth.js → reviews.js → recipes-user.js
   defer гарантирует, что следующий файл стартует только после
   предыдущего, поэтому Ui будет готов к моменту вызова.
   ========================================================================== */

var Ui = {

  /* ------------------------------------------------------------
     СОЗДАТЬ ТЕГ.
     el('p', 'review-date', '3 дня назад')
        → <p class="review-date">3 дня назад</p>

     Аргумент text необязательный: если его не передали (undefined),
     текст не трогаем — тег остаётся пустым контейнером, в который
     потом положат другие теги.

     ВАЖНО ПРО БЕЗОПАСНОСТЬ.
     Внутри — textContent, НИКАКОГО innerHTML. Разница принципиальная:
       innerHTML = 'привет <b>мир</b>'  → браузер РАЗБЕРЁТ текст как
                    HTML, и если в отзыве кто-то напишет
                    '<img src=x onerror=alert(1)>', этот код ВЫПОЛНИТСЯ
                    на странице у всех посетителей (XSS-атака);
       textContent = та же строка станет безобидным текстом: символы
                    < > покажутся как символы.
     Любой текст, который пришёл ОТ ПОЛЬЗОВАТЕЛЯ (ник, отзыв, рецепт),
     вставляется только так.
     ------------------------------------------------------------ */
  el: function (tag, className, text) {
    var node = document.createElement(tag);
    if (className) {
      node.className = className;
    }
    if (text !== undefined && text !== null) {
      node.textContent = String(text);
    }
    return node;
  },

  /* ОЧИСТИТЬ КОНТЕЙНЕР ПЕРЕД ПЕРЕРИСОВКОЙ.
     innerHTML = '' — стандартный способ выбросить всех детей.
     Без этого при каждой перерисовке список рос бы вдвое: старый
     вариант оставался бы под новым. */
  clear: function (node) {
    if (node) {
      node.innerHTML = '';
    }
    return node;
  },

  /* ЗАТЕМНИТЬ/ПОДСВЕТИТЬ ЗАГОЛОВОК СЕКЦИИ, КОГДА её перерисовывают.
     classList.add/remove — добавлять и убирать класс, НЕ затирая
     остальные классы элемента (className = 'x' затёр бы всё). */
  setActive: function (node, className, on) {
    if (!node) {
      return;
    }
    if (on) {
      node.classList.add(className);
    } else {
      node.classList.remove(className);
    }
  },

  /* ------------------------------------------------------------
     ЗВЁЗДЫ РЕЙТИНГА.
     rating — число 1..5, dorey — дробное (например 4.3), его
     округляем В БОЛЬШУЮ сторону до целого: показывать 4.3 как 4 —
     занижать оценку людей.

     ★ и ☆ — просто символы, никакого шрифта иконок не нужно.
     aria-label — подпись для программы чтения с экрана: незрячий
     человек услышит «рейтинг 4 из 5», а не «звезда звезда звезда».
     ------------------------------------------------------------ */
  stars: function (rating) {
    var filled = Math.round(Number(rating) || 0);
    var line = '';
    for (var i = 1; i <= 5; i++) {
      line += i <= filled ? '★' : '☆';
    }
    var box = Ui.el('span', 'stars', line);
    box.setAttribute('aria-label', 'Оценка ' + filled + ' из 5');
    return box;
  },

  /* ------------------------------------------------------------
     СООБЩЕНИЕ ОБ ОШИБКЕ ИЛИ УСПЕХЕ.
     Один узел на форму, в него кладём то, что произошло. kind —
     'error' | 'ok': на них висят разные цвета.
     textContent, а не innerHTML: текст ошибки собирается из того,
     что ввёл пользователь.
     ------------------------------------------------------------ */
  say: function (node, text, kind) {
    if (!node) {
      return;
    }
    node.textContent = text || '';
    node.className = 'form-msg' + (text ? ' form-msg-' + (kind || 'ok') : '');
  },

  /* СОБРАТЬ ЗНАЧЕНИЯ ПОЛЕЙ ФОРМЫ.
     Форма в HTML размечена тегами, а JS просто спрашивает поля по id.
     Возвращает объект с ОБРЕЗАННЫМИ пробелами: пользователь почти
     всегда ставит пробел в конце, и 'admin ' перестал бы быть 'admin'.
     trim() — отрезать пробелы с обоих концов строки. */
  values: function (ids) {
    var out = {};
    for (var i = 0; i < ids.length; i++) {
      var field = document.getElementById(ids[i]);
      out[ids[i]] = field ? field.value.trim() : '';
    }
    return out;
  },

  /* ОЧИСТИТЬ ПОЛЯ ПОСЛЕ УСПЕШНОЙ ОТПРАВКИ. */
  reset: function (ids) {
    for (var i = 0; i < ids.length; i++) {
      var field = document.getElementById(ids[i]);
      if (field) {
        field.value = '';
      }
    }
  },

  /* ------------------------------------------------------------
     СПРЯТАТЬ КАРТИНКИ, КОТОРЫХ НЕТ В ПАПКЕ img/.

     ЗАЧЕМ. В HTML каждая картинка лежит ПОВЕРХ эмодзи (см. блок 9 в
     style.css). Файла ещё нет — браузер показывает серый значок
     «не загрузилось», и вид портится. Эта функция убирает такой img,
     а под ним уже лежит эмодзи. Кинул файл в img/ — картинка
     появилась; убрал — снова эмодзи. Правать HTML каждый раз не нужно.

     КАК ПОНИМАТЬ, ЧТО КАРТИНКИ НЕТ.
     Событие error срабатывает, когда загрузка не удалась. Но у
     отсутствующего файла она часто завершается ЕЩЁ ДО того, как
     отработает defer-скрипт, — подписаться не успеем. Поэтому
     проверяем двумя способами:
       img.complete && img.naturalWidth === 0
         complete — загрузка закончена (успешно или нет);
         naturalWidth — НАСТОЯЩАЯ ширина файла в пикселях. У
         несуществующего файла её нет, то есть 0.
     Если картинка ещё грузится (complete = false), срабатывает
     подписка на error.

     naturalWidth путать с width нельзя: width — это ширина БЛОКА на
     странице (есть всегда), naturalWidth — ширина самого файла.
     ------------------------------------------------------------ */
  fixBrokenPhotos: function () {
    var imgs = document.querySelectorAll('.card-photo > img, .recipe-photo > img');

    for (var i = 0; i < imgs.length; i++) {
      /* ОБРАТИ ВНИМАНИЕ: проверка вынесена в отдельную функцию, а не
         написана прямо в цикле. Внутри цикла на var переменная img ОДНА
         на всех итераций, и обработчик, повешенный в цикле, увидел бы
         к моменту ошибки ПОСЛЕДНЮЮ картинку со страницы — прятались бы
         не те фото. У вызова функции свой аргумент на каждый запуск,
         и замыкание получается правильным. */
      Ui.hideIfBroken(imgs[i]);
    }
  },

  /* Одна картинка: проверить и при необходимости убрать. */
  hideIfBroken: function (img) {
    var hide = function () {
      /* Убираем узел целиком: display:none не помог бы — место под
         картинкой всё равно осталось бы пустым. */
      if (img.parentNode) {
        img.parentNode.removeChild(img);
      }
    };

    if (img.complete && img.naturalWidth === 0) {
      hide();
    } else {
      /* Событие error НЕ ВСПЛЫВАЕТ от img вверх, поэтому слушаем его
         на самом элементе, а не на document. */
      img.addEventListener('error', hide);
    }
  },

  /* ------------------------------------------------------------
     ЗАПУСТИТЬ ФУНКЦИЮ, КОГДА ГОТОВЫ ВСЕ МОДУЛИ.

     Почему нельзя просто вызвать start() в конце файла.
     Файлы с defer выполняются СТРОГО по порядку: store.js, ui.js,
     auth.js, reviews.js, recipes-user.js. Значит в момент, когда
     auth.js дописан и его start() можно вызвать, переменных Reviews и
     UserRecipes ЕЩЁ НЕТ — вызов из auth.js упал бы с «undefined».
     Это видно на странице «Кабинет»: профиль спрашивает количество
     отзывов и список рецептов.

     Событие DOMContentLoaded наступает ПОСЛЕ того, как выполнены ВСЕ
     скрипты с defer. Подписка на него — способ сказать: «подожди,
     пока соберутся все модули, потом зови».

     Ограничение, о котором честно: если скрипт вставляют на страницу
     динамически ПОСЛЕ загрузки (createElement('script')), событие уже
     прошло и start не вызовется. Так подключают только рекламные
     блоки; у нас все скрипты стоят в HTML.
     ------------------------------------------------------------ */
  onReady: function (fn) {
    document.addEventListener('DOMContentLoaded', fn);
  }
};

/* Картинки чиним СРАЗУ, не дожидаясь DOMContentLoaded.
   Скрипт подключён с defer, значит DOM уже построен, а скрытие
   битого файла лучше сделать до первой отрисовки — иначе мигнёт
   серый значок. Обработчик error, повешенный здесь, ловит и те
   файлы, что дочитались позже. */
Ui.fixBrokenPhotos();
